        $lang = 'tr'
    }
    if ($lang -like 'tr*') {
        $Script:AmfetaminLang = 'tr'
    } else {
        $Script:AmfetaminLang = 'en'
    }
}

function T {
    param(
        [Parameter(Mandatory)][string]$Key,
        [object[]]$FormatArgs
    )
    $table = if ($Script:AmfetaminLang -eq 'tr') {
        $Script:AmfetaminStringsTr
    } else {
        $Script:AmfetaminStringsEn
    }
    $text = if ($table.ContainsKey($Key)) { $table[$Key] } else { $Key }
    if ($null -ne $FormatArgs -and $FormatArgs.Count -gt 0) {
        return [string]::Format($text, $FormatArgs)
    }
    return $text
}
